## Почему одного размера листа недостаточно

Цена зависит от объёма и сложности обработки. Внешний контур, отверстия и углубления задают разные траектории инструмента. На расчёт могут влиять подготовка файла, способ крепления и необходимость дополнительной обработки.

Число деталей тоже нужно назвать сразу. Одна деталь и партия одинаковых изделий могут иметь разное распределение подготовительных затрат. Но автоматически обещать скидку за тираж нельзя: условия определяются по заданию.

## Что означает цена за метр реза

У некоторых исполнителей в прайсах указана стоимость за погонный метр. Это длина траектории реза, а не площадь листа и не длина одной стороны детали. В тарифе могут быть ограничения по материалу, толщине и объёму заказа.

Такой прайс не всегда подходит для оценки углублений или сложной обработки. Спросите, какие операции он покрывает и что считается отдельно. Публичного подтверждённого тарифа FAKTURA для всех задач в этой статье нет, поэтому чужие ставки мы не приводим как свои.

## Как сравнить два предложения

Отправьте одинаковое задание и попросите перечислить состав работ. Проверьте:

- включён ли материал или оплачивается отдельно;
- входит ли подготовка производственного файла;
- учтены ли все отверстия, пазы и углубления;
- требуется ли дополнительная обработка кромок и поверхности;
- включены ли упаковка и доставка, если они нужны;
- какие сроки и требования к готовым деталям согласованы.

Если в одном предложении есть только фрезеровка, а в другом также материал и отделка, сравнивать итоговые суммы напрямую нельзя. Сначала приведите предложения к одному составу работ.

