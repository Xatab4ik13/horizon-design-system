ДУБ

Плотный, тяжёлый, стабильный. Держит влажность квартиры без капризов, поэтому дубовая мебель спокойно живёт рядом с батареей. Выраженный рисунок с крупными порами, тон от медового до почти чёрного при тонировке. Царапины на нём заметны меньше, чем на светлых породах, - рисунок их прячет.

