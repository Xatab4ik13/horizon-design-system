Масло-воск - это состав из натуральных масел (чаще всего льняного) и твёрдых восков (карнаубского, канделильского, пчелиного). Масло проникает вглубь древесины и защищает её изнутри, а воск остаётся на поверхности и даёт шелковистый, приятный на ощупь финиш.

