Цельный массив - деталь выпилена из одного куска дерева. Мебельный щит - склейка из ламелей, по свойствам близка к массиву, часто даже стабильнее, и это нормальный честный материал. Шпон - тонкий срез настоящего дерева, наклеенный на плиту. ЛДСП и МДФ с декоративной пленкой - древесно-плитные материалы, где фактура дерева воспроизводится печатью.

ШЕСТЬ ПРОВЕРОК

1. Торцы. Главный индикатор. У массива рисунок на лицевой стороне переходит на торец и продолжается логично. У шпона торец либо заклеен кромкой, либо рисунок на нём «обрывается» и не совпадает с лицом.

2. Рисунок. У настоящего дерева он нигде не повторяется. Если на двух дверцах шкафа вы видите одинаковый узор - это плёнка или шпон с одной и той же матрицы.

3. Сучки. У массива сучок виден с обеих сторон детали и в одном и том же месте. Нарисованный сучок - только с лица.

4. Вес. Массив дуба тяжёлый, ощутимо тяжелее МДФ того же размера. Комод из «дуба», который вы легко двигаете одной рукой, дубом не является.

5. Звук и ощущение. Постучите пальцем: массив отзывается глухо и плотно, полая плита - гулко.

6. Низ и задняя стенка. Производители экономят там, куда не смотрят. Загляните под столешницу и за шкаф: там часто видно, из чего сделан корпус на самом деле.

