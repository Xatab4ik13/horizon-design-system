## Браширование: фактура, которую чувствует рука

Браширование - это выборка мягких волокон жёсткой металлической щёткой. Твёрдые гребни годичных колец остаются, мягкие углубляются - поверхность становится рельефной, с выраженной текстурой на ощупь.

Где это работает лучше всего:

- [панно на стену](/catalog) - рельеф даёт тени, рисунок оживает при боковом свете;
- фасады и столешницы в стиле кантри и лофт;
- двери и мебельные фасады, когда требуется выразительная фактурная поверхность.

Классическая связка - браширование + двухцветная тонировка: сначала тёмный тон втирается в углубления, потом поверхность слегка шлифуется и покрывается светлым. Гребни светлеют, поры остаются тёмными - получается та самая дорогая глубина, которую не даёт ни одна плёнка.

