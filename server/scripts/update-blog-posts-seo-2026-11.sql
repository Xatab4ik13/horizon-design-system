Выбор породы: это баланс твердости, текстуры и стоимости заготовки. В столярном деле часто сравнивают четыре распространенные породы: дуб, ясень, бук и сосну. Разберем свойства и особенности каждой.

## Дуб - максимальная долговечность

- **Твёрдость:** одна из самых твёрдых доступных пород. Столешница из дуба переживёт десятилетия активной эксплуатации.
- **Текстура:** крупные выразительные годичные кольца, красивые «зеркала» на радиальном распиле.
- **Нюансы:** тяжёлый, дороже остальных, содержит дубильные вещества - при контакте с железом и влагой может темнеть.
- **Где лучше всего:** столешницы, двери, лестницы, долговечные предметы интерьера.

## Ясень - прочность и светлая текстура

- **Твёрдость:** сопоставим с дубом, иногда даже твёрже.
- **Текстура:** светлая, с контрастным рисунком - отлично смотрится в современных интерьерах и при тонировании.
- **Нюансы:** чуть менее стабилен к перепадам влажности, чем дуб.
- **Где лучше всего:** [панно на стену](/catalog), столешницы, мебель в светлых интерьерах.

## Бук - ровность и спокойствие

- **Твёрдость:** высокая, ближе к дубу, чем к сосне.
- **Текстура:** мелкая, однородная, розовато-кремовый оттенок. Идеален, когда дерево должно быть фоном, а не акцентом.
- **Нюансы:** боится влаги - не лучший выбор для ванной без дополнительной защиты.
- **Где лучше всего:** мебельные фасады, стеллажи, стулья, детская мебель.

## Сосна - доступность и тепло

- **Твёрдость:** мягкая порода. Вмятины от ударов - вопрос времени, но многим нравится эта «жизнь» дерева.
- **Текстура:** тёплый желтоватый оттенок, заметные сучки - тот самый «дачно-скандинавский» характер.
- **Нюансы:** смолистость, со временем желтеет сильнее.
- **Где лучше всего:** дачная мебель, двери, каркасные конструкции, заготовки для творчества.

