## Практично, если знать три вещи

Первая - **порода**. Для кухонных поверхностей традиционно выбирают плотные лиственные породы: дуб или ясень. Они лучше переносят бытовые механические нагрузки, хотя резать продукты прямо на дереве без разделочной доски в любом случае не стоит.

Вторая - **зона у мойки**. Это единственное по-настоящему уязвимое место. Вода у раковины стоит постоянно, и за пять-семь лет покрытие там устаёт. Делается так: зону вокруг мойки периодически обновляют подходящим защитным составом по инструкции производителя либо устанавливают накладную или каменную мойку, снижая контакт массива с постоянной сыростью.

Третья - **уход**. Дерево не прощает одного: оставленной на ночь лужи. Всё остальное оно прощает.

