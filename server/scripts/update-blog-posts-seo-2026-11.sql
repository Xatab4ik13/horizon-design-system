## Как создаются столы с эпоксидной смолой

Основа конструкции - слэбы: продольные распилы дерева с естественным краем. Для таких проектов часто подбирают древесину с выразительной текстурой, например орех, которая эффектно контрастирует со смолой.

Процесс выглядит так:

1. Подбирают и подготавливают сухую древесину, согласуют геометрию заготовок.
2. Собирают герметичную форму для заливки.
3. Заливают совместимый эпоксидный состав по его технической карте: толщина слоя и температурный режим зависят от продукта.
4. Выдерживают материал до завершения предусмотренного цикла отверждения.
5. Шлифуют и выполняют отделку, подходящую для запланированного применения.

Пигмент для «реки» подбираем под интерьер: прозрачный, дымчатый, синий, глубокий чёрный. Металлические пигменты дают эффект перелива - красиво, но на любителя.

## Плюсы, из-за которых их заказывают

- **Каждый стол - единственный.** Текстура дерева не повторяется, рисунок смолы тоже.
- **Это акцент.** Такой стол собирает вокруг себя всю комнату, остальной мебели можно быть скромной.
- **Смола герметизирует дефекты.** Трещины и сучки превращаются в часть дизайна.

## Минусы, о которых молчит реклама

Вот здесь начинается честная часть:

- **Смола подвержена царапинам.** Твёрдость зависит от состава, а посуда и твёрдые предметы могут оставлять следы на поверхности. Матовая финишная шлифовка маскирует их лучше глянца.
- **Риск изменения цвета под УФ.** Под прямыми солнечными лучами нестойкие составы желтеют со временем. Для качественных изделий подбирают специальные смолы с УФ-стабилизаторами.
- **Горячее ставить нельзя.** Кружка чая - пожалуйста, сковорода - нет. Останется светлое пятно.
- **Ремонт сложнее.** Подмять масло на дереве - дело вечера. Перешлифовать смолу - работа мастерской.

## Кому «река» подходит, а кому - нет

Берите, если хотите эффектный стол для гостиной или кабинета и готовы относиться к нему чуть бережнее, чем к обычному. Для кухни, где поверхность подвергается регулярным механическим и температурным нагрузкам, практичнее рассмотреть классическую массивную поверхность со специальным защитным покрытием.

