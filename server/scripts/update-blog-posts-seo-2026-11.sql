Минеральное масло пищевого класса или специальная смесь масла с пчелиным воском. Обычное подсолнечное или оливковое не годится: оно не высыхает, а прогоркает, и через пару месяцев доска пахнет старым жиром.

При обработке новой доски важно следовать инструкции производителя конкретного состава. Обычно масло наносят равномерным слоем, дают впитаться и тщательно убирают излишки, повторяя процедуру по мере необходимости. Периодичность обновления зависит от условий эксплуатации: уход требуется, когда вода перестает собираться каплями и начинает впитываться.

МОЖНО ЛИ В ПОСУДОМОЙКУ

Нет. Ни одну деревянную доску. Горячая вода плюс агрессивная химия плюс сушка - и через несколько циклов склейка расходится, а доска коробится «лодочкой». Это самый частый способ убить хорошую доску за месяц.

Правильно: помыть под тёплой водой с обычным средством, сразу вытереть насухо и поставить на ребро, чтобы обе стороны сохли одинаково. Доска, оставленная сохнуть плашмя, выгибается.

ЗАПАХ И ГИГИЕНА

Чеснок, рыба, лук: соль плюс половинка лимона, потереть, смыть, высушить. Раз в пару месяцев можно пройтись слабым раствором уксуса.

Вопреки мифу, дерево в этом смысле не опаснее пластика: у многих пород есть природные антибактериальные свойства, а бактерии, попавшие в микротрещины, там же и погибают при высыхании. Главное правило одно - доска должна успевать высыхать.

КОГДА ДОСКУ ПОРА ОБНОВИТЬ

Глубокие борозды, в которых задерживается влага, повод для локальной перешлифовки. Поверхность последовательно обрабатывают абразивами от грубого к более тонкому зерну и заново покрывают защитным маслом по инструкции к составу. Дерево ремонтопригодно, поэтому при аккуратном уходе доска служит долго.

