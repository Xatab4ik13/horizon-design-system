## Чем масло-воск отличается от лака

Лак образует на поверхности полимерную пленку. Лаки бывают глянцевыми, матовыми, а также на водной основе, однако при локальном повреждении восстановить участок бесшовно сложнее, чем при масляной отделке.

Масло-воск работает иначе: плёнки нет, древесина остаётся живой на ощупь, а царапина убирается локальной шлифовкой и повторным нанесением состава только на это место.

## Плюсы масла-воска

1. **Назначение состава.** Допуск к контакту с пищей и пригодность для детских игрушек проверяются отдельно по документам продукта. EN 71.3 относится к игрушкам и не заменяет подтверждение пригодности для разделочной доски.
2. **Ремонтопригодность.** Некоторые составы допускают локальное обновление; способ ремонта и время сушки берут из инструкции.
3. **Внешний вид.** Степень блеска и изменение оттенка зависят от выбранного продукта и древесины.
4. **Текстура.** Масляная отделка может подчёркивать рисунок волокон, но результат лучше оценивать на образце.

## Минусы - честно

- Пролитую воду лучше удалить сразу, не оставляя поверхность мокрой.
- Защитный слой может требовать обновления по мере износа.
- Межслойная сушка и полное отверждение могут занимать разное время: ориентируйтесь на техническую карту конкретного продукта, а не на универсальный срок.

## Как обновить покрытие

Технология обновления зависит от рекомендаций производителя конкретного состава. Обычно поверхность очищают от загрязнений, при необходимости аккуратно матируют мелким абразивом вдоль волокон и наносят тонкий слой масла-воска с удалением излишков и соблюдением указанного времени сушки.

