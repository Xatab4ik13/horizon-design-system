Запах новой мебели зависит от примененных финишных материалов: натуральные масла и воски имеют характерный масляный аромат, а лаки или эмали могут иметь технический запах в период высыхания. Резкий химический запах плитных материалов требует проверки сертификатов эмиссии (класс E1 или E0.5), так как сам по себе запах не является точным методом определения формальдегида.

