Рисунок и край каждого спила отличаются. Это особенность натуральной древесины, но выразительная индивидуальная текстура встречается и в других изделиях из массива.

## Породы древесины для слэбов

В столярном производстве для массивных плит применяют разные породы:

- **Дуб**: плотный материал с выразительной текстурой, традиционный выбор для столешниц.
- **Ясень**: светлая древесина с контрастными годичными кольцами, удобная для тонирования.
- **Клен и орех**: ценные породы с богатым природным рисунком и стабильной структурой.

О свойствах пород подробнее - в нашей [статье-разборе](/blog/porody-dereva-dlya-mebeli).

## Трещины и пустоты: это норма

У большого спила почти всегда есть трещины от усушки и сучковые карманы. Их не прячут, а работают с ними: торцы трещин стягивают «бабочками» (врезными шпонками банта-образной формы) - это и усиление, и декор. Пустоты по желанию клиента заливают эпоксидной смолой - прозрачной, тонированной или чёрной.

Важный момент: трещины должны быть стабилизированы до покрытия. Если мастер просто зашпаклевал свежую трещину в сыром слэбе - через год она поедет дальше.

