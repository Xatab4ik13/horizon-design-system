## Главный враг - перепады влажности

Дерево дышит: зимой в отапливаемой квартире оно усыхает, летом набирает влагу. Микродвижения - норма, а вот резкие перепады опасны:

- держите влажность в доме в районе 40-60% (увлажнитель зимой решает половину всех «деревянных» проблем);
- не сушите мокрые вещи на двери и не ставьте рядом обогреватели;
- ванная - особая зона: дверь туда нужна с качественной влагостойкой отделкой и вентиляцией.

Если дверь зимой чуть поскрипывает или летом плотнее закрывается, это может быть сезонной реакцией материала на влажность. При значительном перекосе обычно требуется точная регулировка петель или геометрии полотна.

## Чем мыть и чем не мыть

**Можно:** мягкая ткань, слегка влажная, или сухая для пыли. Для загрязнений - капля нейтрального мыла в воде, потом сразу вытереть насухо.

**Нельзя:** абразивные губки и порошки (царапают покрытие), средства с аммиаком и спиртом (разрушают лак и масло), «обильный» мокрый уход - вода не должна стекать по полотну и скапливаться в филёнках.

