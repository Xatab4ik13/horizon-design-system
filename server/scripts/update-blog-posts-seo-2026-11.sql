Клеёный щит часто ругают зря. Из-за разнонаправленных ламелей он меньше ведёт при перепадах влажности, чем цельная доска той же ширины. В корпусной мебели - шкафах, комодах, кухнях - это правильный инженерный выбор, а не удешевление. Цельный массив принципиален там, где деталь несёт нагрузку или видна с торца: столешницы, царги, ножки.

