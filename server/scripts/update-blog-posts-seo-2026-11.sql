Крепление к слэбу - плавающее: спил живёт и двигается по влажности сильнее клеёного щита.

## Частые вопросы

### Слэб или клееный щит: что стабильнее?
Клееный щит геометрически стабильнее, так как внутренние напряжения древесины в нем скомпенсированы. Слэб ценят за природный рисунок и живой край. При грамотной сушке, компенсации напряжений и правильном уходе изделие из слэба сохраняет свои качества на долгие годы.

### Эпоксидная заливка обязательна?
Нет. Многие спилы красивы без неё. Смола - способ обыграть пустоты, а не необходимость.

### Почему цены на слэбы так различаются?
Цена - это ширина и порода спила плюс годы сушки. Широкий дубовый слэб без сучков - редкость, и стоит соответствующе.

