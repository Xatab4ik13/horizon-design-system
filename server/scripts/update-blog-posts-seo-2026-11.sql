## Какая порода под какую технику

**Декупаж и роспись акрилом** - липа и берёза: мелкая однородная текстура не спорит с рисунком, краска ложится ровно.

**Выжигание** - липа: мягкая, светлая, без смолистых карманов. Сосна хуже: смола плавится и пачкает жалo паяльника.

**Резьба** - липа для начинающих (мягкая, режется легко в любом направлении), бук для опытных (твёрже, но держит мелкую деталь).

**Тонировка и браширование** - ясень и сосна с выраженной текстурой: браширование проявляет годичные кольца.

## На что смотреть при выборе заготовки

1. **Качество шлифовки.** Проведите рукой: не должно быть ворса, следов фрезы и сколов на кромках. Каждая доработка - ваше время.
2. **Влажность древесины.** Сырая основа со временем растрескается под слоем краски. Надежнее выбирать материал камерной сушки с влажностью в пределах 8-10%.
3. **Отсутствие покрытия.** Лак или масло под краской - лишний слой, который мешает адгезии. Заготовка должна быть «голой».
4. **Сучки.** Для росписи лучше бессучковый массив; для эко-стиля сучки - наоборот, изюминка.

