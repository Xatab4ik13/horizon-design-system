$article$## Почему дверь из массива

Межкомнатные двери из массива дерева - это вес, звук, тактильность и срок службы, который не даёт ни одна пустотелая дверь с сотовым наполнителем. Такая дверь не «бухтит» при закрытии, лучше держит звукоизоляцию и ремонтопригодна: её можно шлифовать и перетонировать.

В столярном производстве двери изготавливаются под конкретные проемы и задачи интерьера. Ниже разберем базовые конструктивные типы.

## Виды конструкций

### Филёнчатые

Классика: каркас (обвязка) из массивного бруса + вставки-филёнки, которые «плавают» в пазах. Филёнка не вклеена жёстко - это позволяет дереву двигаться при изменении влажности без трещин. Самая надёжная и ремонтопригодная конструкция.

### Щитовые

Полотно из клеёного щита, покрытое шпоном или массивными накладками. Ровная глухая поверхность - под современные интерьеры. Важно, чтобы в основе был именно клеёный щит из массива, а не МДФ с «деревянной» плёнкой.

### Со стеклом

Филёнчатая конструкция, где часть филёнок заменена стеклом: матовым, тонированным, витражным. Пропускают свет между комнатами - актуально для тёмных коридоров.

## Породы дерева для дверей

**Дуб** - твердая порода с выразительной текстурой волокон, устойчивая к бытовым повреждениям. Полотно из дуба имеет ощутимый вес, поэтому требует надежной фурнитуры и прочного короба.

**Ясень** - по механической прочности близок к дубу, отличается ярким фактурным рисунком и широким диапазоном оттенков при тонировании.

