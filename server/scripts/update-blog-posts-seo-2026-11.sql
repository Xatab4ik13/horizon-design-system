ТОРЦЕВАЯ ИЛИ ОБЫЧНАЯ

Обычная (пластовая) доска - это щит, где волокна лежат вдоль поверхности. Нож режет волокно поперёк, на доске со временем появляются заметные борозды.

Торцевая - склейка из брусков, поставленных торцом вверх. Нож входит между волокнами, и они частично смыкаются обратно. Такая доска дольше остаётся ровной и заметно мягче к лезвию, но толще, тяжелее и стоит в два-три раза дороже: в ней много работы по склейке.

Если готовите каждый день и ножи у вас хорошие - торцевая окупится. Для нарезки сыра к ужину хватит обычной.

ПОРОДЫ

Хороши: дуб, ясень, бук, клён, вишня, орех. Они плотные, с мелкими порами, не крошатся под ножом.

