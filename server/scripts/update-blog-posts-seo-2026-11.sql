ПОРОДЫ: ЧТО РЕАЛЬНО МЕНЯЕТСЯ

Сосна. Самый доступный массив. Мягкая, лёгкая, тёплая на ощупь. Минус один и честный: на мягком дереве остаются вмятины от удара углом тумбочки или каблуком. Для гостевой комнаты, дачи, детской - отличный вариант.

Берёза. Плотнее сосны, рисунок спокойный, почти без выраженных полос. Хорошо красится в любой цвет, если нужна кровать не «под дерево», а под интерьер.

Бук. Тяжёлый и очень прочный, но чувствителен к влажности: в комнате с сухим воздухом зимой и открытыми окнами летом может вести. Если у вас тёплый пол или батарея прямо под кроватью - лучше не он.

Дуб. Плотная древесина с выразительной текстурой и хорошей стойкостью к бытовым повреждениям. Как и другие породы, реагирует на влажность: долговечность зависит от конструкции, подготовки материала и условий в помещении.

Ясень. По прочности рядом с дубом, рисунок выразительнее, тон светлее. Берут, когда хочется массив, но не хочется «тяжёлой» тёмной спальни.

ПОЧЕМУ КРОВАТИ СКРИПЯТ

Почти никогда не из-за породы. Скрип - это трение дерева о дерево или разболтанное соединение. Три главные причины:

1. Ламели лежат в пластиковых держателях, которые со временем разбиваются.
2. Царги притянуты обычными саморезами вместо стяжек - за год соединение расшатывается.
3. Дерево было недосушено, и после усадки все стыки ослабли.

Уточните подготовку древесины и тип соединения боковых деталей с изголовьем и изножьем. Скрип может быть связан с ослабленным крепежом или трением деталей; правильное решение выбирают после проверки конструкции.

