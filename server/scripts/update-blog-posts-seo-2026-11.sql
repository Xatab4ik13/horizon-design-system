Древесина - гигроскопичный материал: она отдаёт влагу в сухой воздух и впитывает её из влажного. При этом дерево меняет размеры - и, что важно, **неравномерно**: поперёк волокон усушка в разы больше, чем вдоль. Именно поэтому широкие щиты (столешницы, дверные полотна) реагируют на сезонность сильнее всего.

Это не дефект, а свойство материала. Задача - держать эти колебания в безопасном диапазоне.

## Какая влажность нужна древесине

Оптимум для мебели из массива в жилом помещении:

- **влажность воздуха: 40–60%;**
- **температура: 18–24 °C;**
- без резких перепадов.

Главный враг - отопительный сезон: в квартирах зимой влажность падает до 20–30%, и дерево начинает отдавать влагу и усыхать. Второй враг - прямая близость к батареям и тёплым полам: локальный перегрев сушит изделие неравномерно, отсюда коробление.

## 6 правил, которые продлят жизнь мебели

1. Следите за влажностью помещения и рекомендациями изготовителя изделия.
2. Не допускайте локального перегрева и длительного намокания.
3. Проверяйте, не мешает ли крепление естественному движению широких деревянных деталей.
4. Соблюдайте правила очистки и обновления [конкретного покрытия](/blog/maslo-vosk-dlya-dereva-pokrytie).
5. При новых трещинах или деформации обращайтесь к специалисту, а не маскируйте причину.

## Если трещина уже появилась

Небольшую трещину (до 1–2 мм) можно устранить самостоятельно:

Если появилась трещина, зафиксируйте её на фото и уточните состояние покрытия, креплений и влажность в комнате. Не заполняйте дефект случайным составом до выяснения причины: вмешательство может осложнить ремонт. Сквозные трещины и повреждения соединений требуют оценки специалиста.

Сквозные трещины в щитах и расхождение клеевых швов требуют столярного вмешательства: для восстановления геометрии деталь переклеивают или стягивают специальными шпонками.

