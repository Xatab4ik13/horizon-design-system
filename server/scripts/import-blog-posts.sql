- **Дешёвая смола желтеет.** На солнечной стороне комнаты экономия на смоле вылезает через год-два. Мы работаем только со стойкими к УФ составами, и это одна из причин цены.
- **Горячее ставить нельзя.** Кружка чая — пожалуйста, сковорода — нет. Останется светлое пятно.
- **Ремонт сложнее.** Подмять масло на дереве — дело вечера. Перешлифовать смолу — работа мастерской.

## Кому «река» подходит, а кому — нет

Берите, если хотите эффектный стол для гостиной или кабинета и готовы относиться к нему чуть бережнее, чем к обычному. Для кухни, где столешницу каждый день режут, льют и ставят горячее, мы честнее посоветуем [классическую столешницу из массива](/catalog) — она терпит почти всё.

## Сколько стоит и сколько ждать

Цена зависит от размера, породы дерева и объёма смолы — её в «реке» уходят буквально литры, а стоит она недёшево. Ориентир: стол-«река» заметно дороже аналогичного по габаритам стола из чистого массива. По срокам закладывайте от трёх недель — торопить полимеризацию нельзя, это тот случай, когда спешка портит всё.

