**Смола токсична?**
Жидкая — да, работать с ней нужно в защите. После полной полимеризации качественная смола инертна и безопасна, в том числе для контакта с пищей (у пищевых составов есть соответствующие сертификаты).

**А если смола поцарапалась?**
