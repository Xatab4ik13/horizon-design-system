## Правило первое: не больше двух-трёх пород на комнату

У каждой породы свой рисунок: спокойный у бука, выразительный у ясеня, роскошный у ореха. Пять пород в одной комнате — это пять разных рисунков, которые спорят между собой.

Рабочая схема: одна доминирующая порода (обычно пол или крупная мебель), вторая поддерживающая и третья — акцентная, в малых предметах. Дальше — стоп.

## Правило второе: держитесь одной температуры

Оттенки дерева делятся на тёплые (дуб коньячный, вишня, сосна мёдовая) и холодные (белёный дуб, ясень под серым тоном, венге). Смешивать температуры можно, но это высший пилотаж — в большинстве интерьеров спокойнее держаться одной стороны.

