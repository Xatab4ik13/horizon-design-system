## Ошибки, которые мы видим чаще всего

- **«Дерево к дереву» по принципу «какое нашлось».** Сосна, дуб и венге в одной комнате без системы — визуальный шум.
- **Слишком много одного рисунка.** Комната целиком в ясене с его активной текстурой утомляет. Яркой породе нужны спокойные соседи.
- **Игнорирование отделки.** Рыжий лак из девяностых убивает даже хорошую мебель. Современное тонирование и масло-воск дают совсем другой, глубокий цвет — мы подробно писали об этом в [статье про тонирование и браширование](/blog).
- **Боязнь тёмного дерева.** На практике тёмные предметы собирают светлые интерьеры лучше любого декора.

